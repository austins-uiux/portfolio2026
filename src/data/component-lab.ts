export const labGroups = Object.keys(groups) as LabGroup[];
export const labComponents = catalog.map((item) => ({
  ...item,
  group:
    labGroups.find((group) => groups[group].includes(item.id)) ??
    ('표시' as LabGroup),
  description: descriptions[item.id],
}));
export const getLabComponent = (id: string) =>
  labComponents.find((item) => item.id === id);
export type LabComponent = (typeof labComponents)[number];
