export const interactionGroups = Object.keys(groups) as InteractionGroup[];
export const interactionComponents = catalog.map((item) => ({
  ...item,
  group:
    interactionGroups.find((group) => groups[group].includes(item.id)) ??
    ('특수효과' as InteractionGroup),
  description: descriptions[item.id],
}));
export const getInteractionComponent = (id: string) =>
  interactionComponents.find((c) => c.id === id);
export type InteractionComponent = (typeof interactionComponents)[number];
